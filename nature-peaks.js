for (const [slug, name, elevation, point, website, aliases] of bieszczadyPeaks) {
  const summit = {elevation, aliases:aliases ?? '', mapQuery:point?.join(',')};
  if (slug === 'tarnica') {
    const tarnica = destinations.find(place => place.id === 'tarnica');
    Object.assign(tarnica, summit, {tags:[...tarnica.tags, 'szczyt'], trailhead:'Punkt kasowy BdPN Wołosate'});
    continue;
  }
  destinations.push({
    id:'peak-'+slug, summitKey:slug, name, town:'Bieszczady', region:'bieszczady', tags:['szczyt'],
    description:'Wierzchołek z wykazu Bieszczadów.', website:website ?? natureSources.peaks,
    catalogOnly:true, ...summit,
  });
}

